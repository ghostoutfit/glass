// Dev-only: regenerate the bundled Bulk candidate states and write them into the repo as a
// data module the app imports at startup. Run this (node scripts/gen-candidates.mjs) after
// tweaking the sand melt physics or the macroMeltTarget curve. End users never generate.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import {
  initSandParticles, mergeSodaGrains, mergeSilicateGrains, convertLargeNaGrains,
  absorbNearbyGrains, stepNaBlobSprings, stepSandPhysics, checkNaBlobMerges, snapshotSand,
} from '../v4/sandPhysics.js'

// --- must match the live Bulk tab + GlassViewer ---
const BOX_SIZE = 320, HS = BOX_SIZE / 2, FIXED_DT = 1 / 120
const DRIVE = 1500, GEN_K = 20
const BENCH_TEMPS = [25, 700, 850, 1000, 1150, 1300, 1450, 1600]
const PRESETS = [{ id: 'soda', na2o: 30, nGrains: 2250 }]   // only the mix needs candidates; pure never melts
const macroMeltTarget = T => { const o = 700, f = 1300; const u = Math.max(0, Math.min(1, (T - o) / (f - o))); return u * u * (3 - 2 * u) }
function meld(p, temp, pm) {
  const tf = Math.max(0, Math.min(1, (temp - 700) / 500)), mf = Math.min(1, p.meldCount / p.nNaOriginal)
  const mp = Math.min(1, (tf >= 1 ? 1 : tf * 0.015 * (1 + mf * 5)) * pm), cap = Math.max(1, Math.round(pm))
  if (mp > 0) p.meldCount += mergeSodaGrains(p.sandParticles, mp)
  convertLargeNaGrains(p.sandParticles, p.naBlobs, cap)
  absorbNearbyGrains(p.sandParticles, p.naBlobs, temp, cap)
  const si = Math.max(0, Math.min(1, (temp - 1000) / 200)), sl = Math.max(0, Math.min(1, (temp - 1200) / 200))
  mergeSilicateGrains(p.sandParticles, Math.min(1, si * 0.004 * pm), Math.min(1, sl * 0.004 * pm), Math.max(3, Math.round(3 * pm)))
}
const meltFrac = p => { let s = 0; for (const g of p.sandParticles) if (g.type === 'na-sub') s++; return s / p.nGrainOriginal }

function genTrack(na2o, nGrains) {
  const p = { sandParticles: initSandParticles(HS, true, na2o, nGrains), naBlobs: [], blobMct: {}, meldCount: 0 }
  p.nNaOriginal = p.sandParticles.filter(g => g.type === 'na').length
  p.nGrainOriginal = p.sandParticles.length
  for (let i = 0; i < 20; i++) stepSandPhysics(p.sandParticles, FIXED_DT, HS, 0)
  const out = []; let frame = 0
  for (const T of BENCH_TEMPS) {
    const goal = na2o > 0 ? macroMeltTarget(T) : 0
    let best = -1, stall = 0
    while (true) {
      const f = meltFrac(p)
      if (f > best + 0.002) { best = f; stall = 0 } else stall++
      if (f >= goal || stall > 150) break
      meld(p, DRIVE, GEN_K)
      if (frame % 6 === 0) { stepNaBlobSprings(p.naBlobs, FIXED_DT, 0, T); stepSandPhysics(p.sandParticles, FIXED_DT, HS, 0); checkNaBlobMerges(p.naBlobs, p.blobMct, p.sandParticles, T) }
      frame++
    }
    for (let i = 0; i < 12; i++) stepSandPhysics(p.sandParticles, FIXED_DT, HS, 0)
    out.push({ temp: T, melt: +(meltFrac(p)).toFixed(3), snap: snapshotSand(p) })
  }
  return out
}

const t0 = Date.now()
const data = {}
for (const pr of PRESETS) {
  process.stdout.write(`generating ${pr.id}… `)
  data[pr.id] = genTrack(pr.na2o, pr.nGrains)
  console.log(`done (${data[pr.id].map(c => c.temp + ':' + Math.round(c.melt * 100) + '%').join(' ')})`)
}
const json = JSON.stringify(data)
const header = `// AUTO-GENERATED by scripts/gen-candidates.mjs — do not edit by hand.\n` +
  `// Bulk-tab candidate melt states per preset, keyed by id, at benchmark temperatures.\n` +
  `// Regenerate after changing sand melt physics: node scripts/gen-candidates.mjs\n`
const outPath = join(dirname(fileURLToPath(import.meta.url)), '..', 'v4', 'candidates.generated.js')
writeFileSync(outPath, header + `export const BULK_CANDIDATES = ${json}\n`)
console.log(`wrote ${outPath}  (${(json.length / 1024 / 1024).toFixed(2)} MB, ${Date.now() - t0}ms)`)
