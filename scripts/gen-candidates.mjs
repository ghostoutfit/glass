// Dev-only: regenerate the bundled Bulk candidate states and write them into the repo as a
// data module the app imports at startup. Run this (node scripts/gen-candidates.mjs) after
// tweaking the sand melt physics or the particle melt curve. End users never generate.
// Uses v4/bulkMelt.js — the SAME melt code the live Bulk tab runs — so it can't drift again.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

globalThis.window = globalThis.window ?? {}   // modules read optional window overrides
const { makeBulkGenState, stepBulkGen, BULK_BENCH_TEMPS } = await import('../v4/bulkMelt.js')

// --- must match the live Bulk tab (GlassViewer PRESETS / BOX_SIZE) ---
const BOX_SIZE = 320, HS = BOX_SIZE / 2
const PRESETS = [{ id: 'soda', na2o: 30, nGrains: 2250 }]   // only the mix needs candidates; pure never melts

const t0 = Date.now()
const data = {}
for (const pr of PRESETS) {
  process.stdout.write(`generating ${pr.id} (${BULK_BENCH_TEMPS.join(', ')} °C)… `)
  const G = makeBulkGenState(HS, pr.na2o, pr.nGrains, true)
  stepBulkGen(G, Infinity)
  data[pr.id] = G.out
  console.log(`done (${G.out.map(c => c.temp + ':' + Math.round(c.melt * 100) + '%').join(' ')})`)
}
const json = JSON.stringify(data)
const header = `// AUTO-GENERATED by scripts/gen-candidates.mjs — do not edit by hand.\n` +
  `// Bulk-tab candidate melt states per preset, keyed by id, at benchmark temperatures.\n` +
  `// Regenerate after changing sand melt physics or the particle melt curve: node scripts/gen-candidates.mjs\n`
const outPath = join(dirname(fileURLToPath(import.meta.url)), '..', 'v4', 'candidates.generated.js')
writeFileSync(outPath, header + `export const BULK_CANDIDATES = ${json}\n`)
console.log(`wrote ${outPath}  (${(json.length / 1024 / 1024).toFixed(2)} MB, ${Date.now() - t0}ms)`)
