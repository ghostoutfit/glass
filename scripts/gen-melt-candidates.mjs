// Dev-only: generate the Particles-tab candidate states (heating / slow-cool / fast-cool tracks)
// and write them into v4/candidates.melt.generated.js. Run after tweaking melt physics.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { buildGrid, buildAllAtoms } from '../v4/meltGrid.js'
import { initPhysics, buildRigidBondMap, stepPhysics, snapshotMelt, ENERGY_UNIT } from '../v4/meltPhysics.js'

globalThis.window = globalThis.window ?? {}   // meltPhysics reads window._* tuning knobs (use defaults)
const BENCH = [25, 400, 700, 900, 1050, 1200, 1400, 1600]           // heating benchmarks
const COOL_BENCH = [1600, 1300, 1100, 900, 700, 500, 300, 25]       // cooling benchmarks
const PRESETS = [{ id: 'soda', sio2: 70, na2o: 30, cao: 0 }]
const E = T => (T + 273) * ENERGY_UNIT

function cellData(pr) {
  const types = buildGrid(pr.sio2, pr.na2o, pr.cao)
  const atoms = buildAllAtoms(types, 9)
  return types.map((type, idx) => ({ idx, type, atoms: atoms.filter(a => a.chunkIdx === idx), bonds: [], pts: null, bg: '', bdr: '' }))
}
function fresh(pr) { const p = initPhysics(cellData(pr)); buildRigidBondMap(p); for (let s = 0; s < 10; s++) stepPhysics(p, E(25)); return p }

// Ramp temperature across `steps`, snapshotting whenever we pass a benchmark. mode: null|'slow'|'fast'.
function runTrack(p, fromT, toT, benches, steps, mode) {
  const out = []; const up = toT > fromT; let bi = 0
  for (let s = 0; s <= steps; s++) {
    const T = fromT + (toT - fromT) * (s / steps)
    stepPhysics(p, E(T), 1.0, 0, mode)
    while (bi < benches.length && (up ? T >= benches[bi] : T <= benches[bi])) {
      for (let k = 0; k < 5; k++) stepPhysics(p, E(benches[bi]), 1.0, 0, mode)   // settle at the benchmark
      out.push({ temp: benches[bi], snap: snapshotMelt(p) })
      bi++
    }
  }
  return out
}

const t0 = Date.now()
const data = {}
for (const pr of PRESETS) {
  process.stdout.write(`${pr.id} heating… `)
  const ph = fresh(pr)
  const heating = runTrack(ph, 25, 1600, BENCH, 1200, null)
  process.stdout.write('slow-cool… ')
  const ps = fresh(pr); runTrack(ps, 25, 1600, [1600], 600, null)   // melt first
  const slow = runTrack(ps, 1600, 25, COOL_BENCH, 1440, 'slow')
  process.stdout.write('fast-cool… ')
  const pf = fresh(pr); runTrack(pf, 25, 1600, [1600], 600, null)
  const fast = runTrack(pf, 1600, 25, COOL_BENCH, 600, 'fast')
  data[pr.id] = { heating, slow, fast }
  console.log('done')
}
const json = JSON.stringify(data)
const outPath = join(dirname(fileURLToPath(import.meta.url)), '..', 'v4', 'candidates.melt.generated.js')
writeFileSync(outPath, `// AUTO-GENERATED by scripts/gen-melt-candidates.mjs — do not edit.\nexport const MELT_CANDIDATES = ${json}\n`)
console.log(`wrote ${outPath}  (${(json.length / 1024 / 1024).toFixed(2)} MB, ${((Date.now() - t0) / 1000).toFixed(1)}s)`)
